/**
 * Register the Spanish bundle. The en bundle goes UNDER it
 * (merge-priority convention): a key this locale has not translated yet
 * degrades to ENGLISH, never to a raw key.
 */
export function registerModerationI18nEs(
  engine: I18nEngine,
  locale = "es"
): void {
  engine.registerBundle(locale, moderationI18nBundleEn);
  engine.registerBundle(locale, moderationI18nBundleEs);
}
